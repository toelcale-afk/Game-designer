#!/usr/bin/env python3
"""Regenerates the Kotlin copies of files PackFlow embeds in generated projects.

  reusable/error-catcher/*   -> app/src/main/java/com/example/core/ErrorCatcherAssets.kt
  engine/*.js                -> app/src/main/java/com/example/core/EngineAssets.kt

Edit the canonical files, then run: python3 tools/gen_kotlin_assets.py
Unit tests (ErrorCatcherTest, TacticsTemplateTest) fail if the copies drift.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CORE = os.path.join(ROOT, "app/src/main/java/com/example/core")


def read(rel):
    text = open(os.path.join(ROOT, rel), encoding="utf-8").read()
    # Kotlin raw strings can't contain """ and would expand $name / ${...}.
    if '"""' in text or re.search(r"\$[A-Za-z_{]", text):
        sys.exit(f"{rel} contains a Kotlin raw-string hazard (triple quotes or $name)")
    return text


def write(name, obj, consts):
    body = "\n\n".join(f'    const val {k} = """{v}"""' for k, v in consts)
    out = f"""package com.example.core

// GENERATED by tools/gen_kotlin_assets.py from the canonical files. Don't edit by hand.
@Suppress("MaxLineLength")
internal object {obj} {{
{body}
}}
"""
    open(os.path.join(CORE, name), "w", encoding="utf-8").write(out)
    print("wrote", name)


write("ErrorCatcherAssets.kt", "ErrorCatcherAssets", [
    ("JS", read("reusable/error-catcher/error-catcher.js")),
    ("ANDROID_KT_TEMPLATE", read("reusable/error-catcher/android/PackFlowCrashCatcher.kt")),
])
write("EngineAssets.kt", "EngineAssets", [
    ("ENGINE_JS", read("engine/packflow-engine.js")),
    ("TACTICS_JS", read("engine/tactics.js")),
])
